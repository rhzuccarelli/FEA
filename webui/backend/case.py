"""Build code_aster study files (mesh, command file, export file) from a JSON study description."""

from __future__ import annotations

import json
from dataclasses import dataclass

FACES = ("XMIN", "XMAX", "YMIN", "YMAX", "ZMIN", "ZMAX")


@dataclass
class BlockMesh:
    """Structured HEXA8 mesh of a rectangular block, with QUAD4 skin groups per face."""

    nodes: list[tuple[float, float, float]]
    hexas: list[tuple[int, ...]]
    faces: dict[str, list[tuple[int, int, int, int]]]
    face_nodes: dict[str, list[int]]

    @classmethod
    def build(cls, lx, ly, lz, nx, ny, nz):
        def nid(i, j, k):
            return k * (ny + 1) * (nx + 1) + j * (nx + 1) + i

        nodes = [
            (lx * i / nx, ly * j / ny, lz * k / nz)
            for k in range(nz + 1)
            for j in range(ny + 1)
            for i in range(nx + 1)
        ]
        hexas = []
        for k in range(nz):
            for j in range(ny):
                for i in range(nx):
                    hexas.append((
                        nid(i, j, k), nid(i + 1, j, k), nid(i + 1, j + 1, k), nid(i, j + 1, k),
                        nid(i, j, k + 1), nid(i + 1, j, k + 1), nid(i + 1, j + 1, k + 1), nid(i, j + 1, k + 1),
                    ))
        # Skin quads, oriented with outward normals.
        faces = {f: [] for f in FACES}
        for k in range(nz):
            for j in range(ny):
                faces["XMIN"].append((nid(0, j, k), nid(0, j, k + 1), nid(0, j + 1, k + 1), nid(0, j + 1, k)))
                faces["XMAX"].append((nid(nx, j, k), nid(nx, j + 1, k), nid(nx, j + 1, k + 1), nid(nx, j, k + 1)))
        for k in range(nz):
            for i in range(nx):
                faces["YMIN"].append((nid(i, 0, k), nid(i + 1, 0, k), nid(i + 1, 0, k + 1), nid(i, 0, k + 1)))
                faces["YMAX"].append((nid(i, ny, k), nid(i, ny, k + 1), nid(i + 1, ny, k + 1), nid(i + 1, ny, k)))
        for j in range(ny):
            for i in range(nx):
                faces["ZMIN"].append((nid(i, j, 0), nid(i, j + 1, 0), nid(i + 1, j + 1, 0), nid(i + 1, j, 0)))
                faces["ZMAX"].append((nid(i, j, nz), nid(i + 1, j, nz), nid(i + 1, j + 1, nz), nid(i, j + 1, nz)))
        face_nodes = {f: sorted({n for q in quads for n in q}) for f, quads in faces.items()}
        return cls(nodes, hexas, faces, face_nodes)

    def to_aster(self) -> str:
        out = ["TITRE", "Block mesh generated by FEA web UI", "FINSF", "COOR_3D"]
        out += [f"N{i + 1} {x:.10g} {y:.10g} {z:.10g}" for i, (x, y, z) in enumerate(self.nodes)]
        out += ["FINSF", "HEXA8"]
        out += [f"H{e + 1} " + " ".join(f"N{n + 1}" for n in conn) for e, conn in enumerate(self.hexas)]
        out += ["FINSF", "QUAD4"]
        names = {}
        q = 0
        for face, quads in self.faces.items():
            names[face] = []
            for conn in quads:
                q += 1
                names[face].append(f"Q{q}")
                out.append(f"Q{q} " + " ".join(f"N{n + 1}" for n in conn))
        out.append("FINSF")
        out += ["GROUP_MA", "VOLUME"] + [f"H{e + 1}" for e in range(len(self.hexas))] + ["FINSF"]
        for face in FACES:
            out += ["GROUP_MA", face] + names[face] + ["FINSF"]
        for face in FACES:
            out += ["GROUP_NO", f"N_{face}"] + [f"N{n + 1}" for n in self.face_nodes[face]] + ["FINSF"]
        out.append("FIN")
        return "\n".join(out) + "\n"

    def surface_triangles(self) -> list[int]:
        """Triangulated skin (0-based node indices) for the browser viewer."""
        tris = []
        for quads in self.faces.values():
            for a, b, c, d in quads:
                tris += [a, b, c, a, c, d]
        return tris

    def edges(self) -> list[int]:
        seen = set()
        lines = []
        for quads in self.faces.values():
            for quad in quads:
                for a, b in zip(quad, quad[1:] + quad[:1]):
                    key = (min(a, b), max(a, b))
                    if key not in seen:
                        seen.add(key)
                        lines += list(key)
        return lines


def validate(study: dict) -> dict:
    """Normalise and sanity-check a study description. Raises ValueError on bad input."""
    g = study.get("geometry", {})
    geo = {k: float(g.get(k, d)) for k, d in (("lx", 1.0), ("ly", 0.1), ("lz", 0.1))}
    geo.update({k: int(g.get(k, d)) for k, d in (("nx", 20), ("ny", 4), ("nz", 4))})
    if min(geo["lx"], geo["ly"], geo["lz"]) <= 0:
        raise ValueError("Block dimensions must be positive")
    if min(geo["nx"], geo["ny"], geo["nz"]) < 1:
        raise ValueError("Element counts must be at least 1")
    if geo["nx"] * geo["ny"] * geo["nz"] > 60000:
        raise ValueError("Mesh too large (limit: 60 000 elements)")

    m = study.get("material", {})
    mat = {"E": float(m.get("E", 210e9)), "nu": float(m.get("nu", 0.3)), "rho": float(m.get("rho", 7850.0))}
    if mat["E"] <= 0 or not (-1 < mat["nu"] < 0.5) or mat["rho"] < 0:
        raise ValueError("Invalid material: need E > 0, -1 < nu < 0.5, rho >= 0")

    bcs = {}
    for face, kind in (study.get("supports") or {}).items():
        if face not in FACES:
            raise ValueError(f"Unknown face {face}")
        if kind not in ("free", "fixed", "roller", "pinned"):
            raise ValueError(f"Unknown support type {kind}")
        if kind != "free":
            bcs[face] = kind

    loads = []
    for ld in study.get("loads") or []:
        face = ld.get("face")
        if face not in FACES:
            raise ValueError(f"Unknown face {face}")
        kind = ld.get("type")
        if kind == "pressure":
            loads.append({"type": kind, "face": face, "value": float(ld.get("value", 0.0))})
        elif kind == "force":
            loads.append({"type": kind, "face": face,
                          **{c: float(ld.get(c, 0.0)) for c in ("fx", "fy", "fz")}})
        else:
            raise ValueError(f"Unknown load type {kind}")

    gr = study.get("gravity") or {}
    gravity = {"enabled": bool(gr.get("enabled", False)), "g": float(gr.get("g", 9.81)),
               "direction": [float(v) for v in gr.get("direction", [0, 0, -1])]}

    an = study.get("analysis") or {}
    analysis = {"type": an.get("type", "static"), "modes": int(an.get("modes", 6))}
    if analysis["type"] not in ("static", "modal"):
        raise ValueError("Analysis type must be 'static' or 'modal'")
    if not 1 <= analysis["modes"] <= 50:
        raise ValueError("Number of modes must be between 1 and 50")

    if not bcs:
        raise ValueError("At least one face must be supported, otherwise the model is a free body")
    if analysis["type"] == "static" and not loads and not gravity["enabled"]:
        raise ValueError("Static analysis needs at least one load or gravity")

    return {"geometry": geo, "material": mat, "supports": bcs, "loads": loads,
            "gravity": gravity, "analysis": analysis}


def face_area(geo: dict, face: str) -> float:
    lx, ly, lz = geo["lx"], geo["ly"], geo["lz"]
    return {"X": ly * lz, "Y": lx * lz, "Z": lx * ly}[face[0]]


def build_comm(study: dict) -> str:
    """Generate a code_aster command file (Python syntax) for the study."""
    geo, mat, an = study["geometry"], study["material"], study["analysis"]
    lines = [
        "# code_aster command file generated by FEA web UI",
        "import json",
        "",
        "DEBUT(LANG='EN')",
        "",
        "mesh = LIRE_MAILLAGE(FORMAT='ASTER', UNITE=20)",
        "",
        "model = AFFE_MODELE(MAILLAGE=mesh,",
        "                    AFFE=_F(TOUT='OUI', PHENOMENE='MECANIQUE', MODELISATION='3D'))",
        "",
        f"steel = DEFI_MATERIAU(ELAS=_F(E={mat['E']!r}, NU={mat['nu']!r}, RHO={mat['rho']!r}))",
        "",
        "mater = AFFE_MATERIAU(MAILLAGE=mesh, AFFE=_F(TOUT='OUI', MATER=steel))",
        "",
    ]

    ddl = []
    for face, kind in study["supports"].items():
        normal = "D" + face[0]
        if kind == "fixed":
            ddl.append(f"_F(GROUP_NO='N_{face}', DX=0.0, DY=0.0, DZ=0.0)")
        elif kind == "roller":
            ddl.append(f"_F(GROUP_NO='N_{face}', {normal}=0.0)")
        elif kind == "pinned":
            # Pinned: in-plane motion blocked, free to move along the face normal.
            tang = [c for c in ("DX", "DY", "DZ") if c != normal]
            ddl.append(f"_F(GROUP_NO='N_{face}', {tang[0]}=0.0, {tang[1]}=0.0)")
    lines += ["supports = AFFE_CHAR_MECA(MODELE=model, DDL_IMPO=(", *[f"    {d}," for d in ddl], "))", ""]

    load_names = []
    pres = [ld for ld in study["loads"] if ld["type"] == "pressure"]
    forces = [ld for ld in study["loads"] if ld["type"] == "force"]
    grav = study["gravity"]
    if an["type"] == "static" and (pres or forces or grav["enabled"]):
        args = []
        if pres:
            args.append("PRES_REP=(" + " ".join(
                f"_F(GROUP_MA='{ld['face']}', PRES={ld['value']!r})," for ld in pres) + ")")
        if forces:
            # Total force on the face, converted to a uniform surface traction.
            items = []
            for ld in forces:
                a = face_area(geo, ld["face"])
                items.append(f"_F(GROUP_MA='{ld['face']}', FX={ld['fx'] / a!r}, "
                             f"FY={ld['fy'] / a!r}, FZ={ld['fz'] / a!r}),")
            args.append("FORCE_FACE=(" + " ".join(items) + ")")
        if grav["enabled"]:
            d = grav["direction"]
            args.append(f"PESANTEUR=_F(GRAVITE={grav['g']!r}, DIRECTION=({d[0]!r}, {d[1]!r}, {d[2]!r}))")
        lines += ["loads = AFFE_CHAR_MECA(MODELE=model,", *[f"    {a}," for a in args], ")", ""]
        load_names.append("loads")

    if an["type"] == "static":
        excit = ", ".join(f"_F(CHARGE={n})" for n in ["supports", *load_names])
        lines += [
            f"resu = MECA_STATIQUE(MODELE=model, CHAM_MATER=mater, EXCIT=({excit},))",
            "",
            "resu = CALC_CHAMP(reuse=resu, RESULTAT=resu,",
            "                  CONTRAINTE=('SIGM_NOEU',), CRITERES=('SIEQ_NOEU',), FORCE=('REAC_NODA',))",
            "",
            "IMPR_RESU(FORMAT='MED', UNITE=80, RESU=_F(RESULTAT=resu))",
            "",
            STATIC_EXTRACT,
        ]
    else:
        lines += [
            "asse = ASSEMBLAGE(MODELE=model, CHAM_MATER=mater, CHARGE=supports, NUME_DDL=CO('numddl'),",
            "                  MATR_ASSE=(_F(MATRICE=CO('stiff'), OPTION='RIGI_MECA'),",
            "                             _F(MATRICE=CO('mass'), OPTION='MASS_MECA')))",
            "",
            "modes = CALC_MODES(MATR_RIGI=stiff, MATR_MASS=mass, OPTION='PLUS_PETITE',",
            f"                   CALC_FREQ=_F(NMAX_FREQ={an['modes']}))",
            "",
            "IMPR_RESU(FORMAT='MED', UNITE=80, RESU=_F(RESULTAT=modes))",
            "",
            MODAL_EXTRACT,
        ]
    lines += ["", "FIN()", ""]
    return "\n".join(lines)


STATIC_EXTRACT = '''# --- Export results as JSON for the web viewer ---
depl = resu.getField('DEPL', 1)
u = {c: depl.getValuesWithDescription(c, [])[0] for c in ('DX', 'DY', 'DZ')}
sieq = resu.getField('SIEQ_NOEU', 1)
vmis = sieq.getValuesWithDescription('VMIS', [])[0]
reac = resu.getField('REAC_NODA', 1)
reaction = [sum(reac.getValuesWithDescription(c, [])[0]) for c in ('DX', 'DY', 'DZ')]
with open('fields.json', 'w') as fobj:
    json.dump({'type': 'static', 'displacement': [u['DX'], u['DY'], u['DZ']],
               'von_mises': vmis, 'reaction': reaction}, fobj)
'''

MODAL_EXTRACT = '''# --- Export results as JSON for the web viewer ---
out = {'type': 'modal', 'modes': []}
params = modes.getAccessParameters()
for rank, freq in zip(params['NUME_ORDRE'], params['FREQ']):
    shape = modes.getField('DEPL', rank)
    comps = [shape.getValuesWithDescription(c, [])[0] for c in ('DX', 'DY', 'DZ')]
    out['modes'].append({'rank': rank, 'frequency': freq, 'shape': comps})
with open('fields.json', 'w') as fobj:
    json.dump(out, fobj)
'''


def build_export(name: str) -> str:
    return "\n".join([
        "P time_limit 900",
        "P memory_limit 2048",
        "P ncpus 1",
        "P mpi_nbcpu 1",
        f"F comm {name}.comm D 1",
        f"F mail {name}.mail D 20",
        f"F rmed {name}.rmed R 80",
        f"F mess {name}.mess R 6",
        "F nom fields.json R 0",
        "",
    ])


if __name__ == "__main__":
    import sys
    s = validate(json.load(open(sys.argv[1])) if len(sys.argv) > 1 else {
        "supports": {"XMIN": "fixed"}, "loads": [{"type": "force", "face": "XMAX", "fz": -1000}]})
    print(build_comm(s))
